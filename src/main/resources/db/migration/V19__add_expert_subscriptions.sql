-- No prices or billing periods are seeded: product policy must be supplied explicitly.
CREATE TABLE subscription_plans (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    grade VARCHAR(20) NOT NULL,
    plan_version INT NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'KRW',
    period_months INT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_subscription_plan_version UNIQUE (grade, plan_version),
    CONSTRAINT ck_subscription_plan_grade CHECK (grade IN ('SPECIAL', 'PREMIUM')),
    CONSTRAINT ck_subscription_plan_amount CHECK (amount > 0 AND amount = FLOOR(amount)),
    CONSTRAINT ck_subscription_plan_currency CHECK (currency = 'KRW'),
    CONSTRAINT ck_subscription_plan_period CHECK (period_months BETWEEN 1 AND 120),
    CONSTRAINT ck_subscription_plan_version CHECK (plan_version > 0)
);

CREATE TABLE expert_subscriptions (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    expert_profile_id BIGINT NOT NULL,
    -- Nullable unique slot: pending/unknown/active subscriptions retain exclusivity.
    current_expert_id BIGINT NULL,
    plan_id BIGINT NOT NULL,
    registration_id VARCHAR(36) NOT NULL,
    customer_ref VARCHAR(40) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    registration_expires_at DATETIME(6) NOT NULL,
    encrypted_billing_key TEXT NULL,
    status VARCHAR(30) NOT NULL,
    current_period_start DATETIME(6) NULL,
    current_period_end DATETIME(6) NULL,
    next_billing_at DATETIME(6) NULL,
    auto_renew BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_subscription_current_expert UNIQUE (current_expert_id),
    CONSTRAINT uk_subscription_registration UNIQUE (registration_id),
    CONSTRAINT uk_subscription_customer UNIQUE (provider, customer_ref),
    CONSTRAINT fk_subscription_expert FOREIGN KEY (expert_profile_id) REFERENCES expert_profiles(id),
    CONSTRAINT fk_subscription_current_expert FOREIGN KEY (current_expert_id) REFERENCES expert_profiles(id),
    CONSTRAINT fk_subscription_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans(id),
    CONSTRAINT ck_subscription_current_expert CHECK (current_expert_id IS NULL OR current_expert_id = expert_profile_id),
    CONSTRAINT ck_subscription_status CHECK (status IN ('REGISTERING', 'PENDING_PAYMENT', 'ACTIVE', 'FAILED', 'EXPIRED'))
);

CREATE TABLE subscription_payments (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    subscription_id BIGINT NOT NULL,
    expert_user_id BIGINT NOT NULL,
    order_id VARCHAR(40) NOT NULL,
    cycle_number INT NOT NULL,
    idempotency_hash VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    grade VARCHAR(20) NOT NULL,
    plan_version INT NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    period_months INT NOT NULL,
    status VARCHAR(30) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    provider_payment_id VARCHAR(200) NULL,
    failure_code VARCHAR(50) NULL,
    paid_at DATETIME(6) NULL,
    period_start DATETIME(6) NULL,
    period_end DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_subscription_payment_order UNIQUE (order_id),
    CONSTRAINT uk_subscription_payment_cycle UNIQUE (subscription_id, cycle_number),
    CONSTRAINT uk_subscription_payment_idempotency UNIQUE (expert_user_id, idempotency_hash),
    CONSTRAINT uk_subscription_provider_payment UNIQUE (provider, provider_payment_id),
    CONSTRAINT fk_subscription_payment_subscription FOREIGN KEY (subscription_id) REFERENCES expert_subscriptions(id),
    CONSTRAINT fk_subscription_payment_user FOREIGN KEY (expert_user_id) REFERENCES users(id),
    CONSTRAINT ck_subscription_payment_amount CHECK (amount > 0 AND amount = FLOOR(amount)),
    CONSTRAINT ck_subscription_payment_currency CHECK (currency = 'KRW'),
    CONSTRAINT ck_subscription_payment_grade CHECK (grade IN ('SPECIAL', 'PREMIUM')),
    CONSTRAINT ck_subscription_payment_cycle CHECK (cycle_number > 0),
    CONSTRAINT ck_subscription_payment_period CHECK (period_months BETWEEN 1 AND 120),
    CONSTRAINT ck_subscription_payment_status CHECK (status IN ('REGISTERING', 'READY', 'PROCESSING', 'PAID', 'FAILED', 'UNKNOWN'))
);
